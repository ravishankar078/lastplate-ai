"""
Route and RouteStop ORM Models.
Enforces multi-stop route optimization structures, sequence order,
service time windows, and stop completion tracking.
"""

from datetime import datetime
from typing import TYPE_CHECKING, List, Optional
import uuid
from sqlalchemy import DateTime, Enum, Float, ForeignKey, Integer, String
from sqlalchemy.dialects.postgresql import UUID
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.db.base import Base, TimestampMixin, UUIDPrimaryKeyMixin

if TYPE_CHECKING:
    from app.models.organization import Organization
    from app.models.pickup import Pickup
    from app.models.user import User


class Route(Base, UUIDPrimaryKeyMixin, TimestampMixin):
    """Volunteer multi-stop route plan generated by Google OR-Tools optimization engine."""

    __tablename__ = "routes"

    volunteer_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("users.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )

    planned_date: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, index=True
    )
    total_distance_km: Mapped[float] = mapped_column(Float, default=0.0, nullable=False)
    total_duration_minutes: Mapped[int] = mapped_column(Integer, default=0, nullable=False)

    status: Mapped[str] = mapped_column(
        Enum(
            "draft",
            "assigned",
            "in_progress",
            "completed",
            "cancelled",
            name="route_status_enum",
            create_type=True,
        ),
        default="draft",
        nullable=False,
        index=True,
    )

    # Relationships
    volunteer: Mapped["User"] = relationship("User", back_populates="routes")
    stops: Mapped[List["RouteStop"]] = relationship(
        "RouteStop",
        back_populates="route",
        order_by="RouteStop.stop_sequence",
        cascade="all, delete-orphan",
    )


class RouteStop(Base, UUIDPrimaryKeyMixin, TimestampMixin):
    """Individual stop in a volunteer route (collection from donor or delivery to recipient)."""

    __tablename__ = "route_stops"

    route_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("routes.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )

    pickup_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("pickups.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )

    organization_id: Mapped[Optional[uuid.UUID]] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("organizations.id", ondelete="SET NULL"),
        nullable=True,
    )

    stop_type: Mapped[str] = mapped_column(
        Enum("pickup", "delivery", name="stop_type_enum", create_type=True),
        nullable=False,
    )
    stop_sequence: Mapped[int] = mapped_column(Integer, nullable=False, index=True)

    address: Mapped[str] = mapped_column(String(255), nullable=False)
    latitude: Mapped[float] = mapped_column(Float, nullable=False)
    longitude: Mapped[float] = mapped_column(Float, nullable=False)

    # Service Window Constraints
    arrival_window_start: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False
    )
    arrival_window_end: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False
    )
    estimated_arrival: Mapped[Optional[datetime]] = mapped_column(
        DateTime(timezone=True), nullable=True
    )
    actual_arrival: Mapped[Optional[datetime]] = mapped_column(
        DateTime(timezone=True), nullable=True
    )

    status: Mapped[str] = mapped_column(
        Enum(
            "pending",
            "arrived",
            "completed",
            "skipped",
            name="stop_status_enum",
            create_type=True,
        ),
        default="pending",
        nullable=False,
    )

    # Relationships
    route: Mapped["Route"] = relationship("Route", back_populates="stops")
    pickup: Mapped["Pickup"] = relationship("Pickup", back_populates="route_stops")
    organization: Mapped[Optional["Organization"]] = relationship("Organization")
